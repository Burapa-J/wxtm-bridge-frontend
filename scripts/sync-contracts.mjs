// Regenerates contracts/abis.ts and contracts/deployments.json from a compiled
// wxtm-bridge-contracts checkout.
//
//   (cd ../wxtm-bridge-contracts && npx hardhat compile)
//   node scripts/sync-contracts.mjs [path/to/wxtm-bridge-contracts]
//
// Review the resulting diff: these addresses are the trust anchor that backend
// chain parameters are checked against (utils/bridge-route.ts).
import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const contractsRepo = resolve(process.argv[2] ?? join(root, '..', 'wxtm-bridge-contracts'))

const CONTRACTS = [
  ['wXTM', 'wXTMAbi'],
  ['wXTMBridge', 'wXTMBridgeAbi'],
  ['wTARI', 'wTARIAbi'],
  ['wTARIBridge', 'wTARIBridgeAbi'],
]
const DEPLOYMENT_KEYS = [
  'wXTM',
  'wXTMBridge',
  'wXTMController',
  'wTARI',
  'wTARIBridge',
  'wTARIController',
  'wTARIBridgeStartBlock',
]

const git = (...args) => execFileSync('git', ['-C', contractsRepo, ...args], { encoding: 'utf8' }).trim()
const SOURCE_PATHS = ['contracts', 'wxtm-bridge-contracts-typechain/deployments']
// The last commit that changed the contract sources or deployments.
const commit = git('log', '-1', '--format=%H', '--', ...SOURCE_PATHS)
if (git('status', '--porcelain', '--', ...SOURCE_PATHS)) {
  throw new Error(`${contractsRepo} has uncommitted contract or deployment changes; sync from a clean commit`)
}

let abis = `// Generated by scripts/sync-contracts.mjs from tari-project/wxtm-bridge-contracts@${commit}.\n// Do not edit by hand.\n`
for (const [name, exportName] of CONTRACTS) {
  const artifact = JSON.parse(
    readFileSync(join(contractsRepo, 'artifacts', 'contracts', `${name}.sol`, `${name}.json`), 'utf8'),
  )
  abis += `\nexport const ${exportName} = ${JSON.stringify(artifact.abi, null, 2)} as const\n`
}
writeFileSync(join(root, 'contracts', 'abis.ts'), abis)

const allDeployments = JSON.parse(
  readFileSync(join(contractsRepo, 'wxtm-bridge-contracts-typechain', 'deployments', 'deployments.json'), 'utf8'),
)
const deployments = {}
for (const [chainId, entries] of Object.entries(allDeployments)) {
  const picked = Object.fromEntries(DEPLOYMENT_KEYS.filter((k) => k in entries).map((k) => [k, entries[k]]))
  if (Object.keys(picked).length) deployments[chainId] = picked
}
writeFileSync(
  join(root, 'contracts', 'deployments.json'),
  `${JSON.stringify({ source: `tari-project/wxtm-bridge-contracts@${commit}`, chains: deployments }, null, 2)}\n`,
)
console.info(`synced contracts from ${commit}`)
